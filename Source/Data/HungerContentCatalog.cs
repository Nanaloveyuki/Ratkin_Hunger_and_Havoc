        internal static IReadOnlyList<HungerHistoryRecord> Histories => histories;
        internal static IReadOnlyList<HungerTraitRecord> Traits => traits;

        internal static HungerHistoryRecord FindHistory(string displayId)
        {
            if (string.IsNullOrEmpty(displayId))
            {
                return null;
            }

            for (int i = 0; i < histories.Length; i++)
            {
                if (string.Equals(histories[i].DisplayId, displayId, StringComparison.OrdinalIgnoreCase))
                {
                    return histories[i];
                }
            }

            return null;
        }

        internal static HungerTraitRecord FindTrait(string displayId)
        {
            if (string.IsNullOrEmpty(displayId))
            {
                return null;
            }

            for (int i = 0; i < traits.Length; i++)
            {
                if (string.Equals(traits[i].DisplayId, displayId, StringComparison.OrdinalIgnoreCase))
                {
                    return traits[i];
                }
            }

            return null;
        }

        internal static float DefaultTraitWeight(string displayId)
        {
            HungerTraitRecord record = FindTrait(displayId);
            if (record == null)
            {
                return 0f;
            }

            float weight = record.Chance * 100f;
            if (weight < 0f)
            {
                return 0f;
            }

            return weight > 100f ? 100f : weight;
        }

        internal static bool IsOwnedHistory(string defName)
        {
            return !string.IsNullOrEmpty(defName) &&
                (defName.StartsWith(HistoryPrefix, StringComparison.Ordinal) ||
                 defName == FallbackChildhood ||
                 defName == FallbackAdulthood);
        }

        internal static bool IsOwnedTrait(string defName)
        {
            return !string.IsNullOrEmpty(defName) && defName.StartsWith(TraitPrefix, StringComparison.Ordinal);
        }
